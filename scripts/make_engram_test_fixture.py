"""Independent synthetic writer for the public .engrampage v1 specification.

The upstream tests refer to private/unpublished converter output. This writer
does not claim to reproduce that converter's provenance or real model weights.
It supplies the same public test geometry with independently generated bytes.
"""
import json
import pathlib
import struct


def main():
    output = pathlib.Path(__file__).resolve().parents[1] / "Tests/Fixtures/deepseek-v41/engram"
    output.mkdir(parents=True, exist_ok=True)
    parts, rows = [], []
    total, values_per_row, scales_per_row = 157, 256, 8
    page_bytes, per_page, header_bytes = 4096, 15, 16384
    row_base = 0
    for part_index, count in enumerate([60, 97]):
        page_count = (count + per_page - 1) // per_page
        data = bytearray(header_bytes + page_count * page_bytes)
        struct.pack_into("<8sIIQQQIIIIQQIIII", data, 0,
                         b"MNRNENG1", 1, header_bytes, total, row_base, count,
                         values_per_row, scales_per_row, page_bytes, per_page,
                         page_count, header_bytes, 0, 0, 32, part_index)
        for local in range(count):
            row = row_base + local
            page_offset = header_bytes + (local // per_page) * page_bytes
            value_offset = (local % per_page) * values_per_row
            scale_offset = per_page * values_per_row + (local % per_page) * scales_per_row
            values = bytes((row * 17 + column * 13) % 256 for column in range(values_per_row))
            scales = bytes(120 + (row + column) % 16 for column in range(scales_per_row))
            data[page_offset + value_offset:page_offset + value_offset + values_per_row] = values
            data[page_offset + scale_offset:page_offset + scale_offset + scales_per_row] = scales
            rows.append(dict(row=row, part=part_index, page_offset=page_offset,
                             value_offset_in_page=value_offset, scale_offset_in_page=scale_offset,
                             values=values.hex(), scales=scales.hex()))
        name = f"synthetic-{part_index}.engrampage"
        (output / name).write_bytes(data)
        parts.append(dict(file=name, part_index=part_index, row_base=row_base, rows=count,
                          pages=page_count, bytes=len(data), page_bytes=page_bytes,
                          scale_offset_in_page=per_page * values_per_row,
                          pad_bytes_per_page=page_bytes - per_page * (values_per_row + scales_per_row),
                          first_page_offset=header_bytes, scale_group_size=32))
        row_base += count
    manifest = dict(table_rows=total, row_value_bytes=values_per_row,
                    row_scale_bytes=scales_per_row, rows_per_page=per_page,
                    parts=parts, rows=rows)
    (output / "engram-fixture.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Generated {total} synthetic rows in two parts; no checkpoint weights")


if __name__ == "__main__":
    main()
